// Package install places the extension where Kodelet discovers it.
package install

import (
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
)

// Plugin layout used by Kodelet discovery.
const (
	PluginName     = "jingkaihe@kodelet-subagent"
	ExtensionName  = "subagent"
	ExecutableName = "kodelet-extension-subagent"
	Repository     = "jingkaihe/kodelet-subagent"
)

// PluginExecutable returns the installed extension path under home.
func PluginExecutable(home string) string {
	return filepath.Join(home, ".kodelet", "plugins", PluginName, "extensions", ExtensionName, ExecutableName)
}

// Plugin atomically copies the source executable to the plugin location
// under home and returns the installed path. Installing again replaces it.
func Plugin(home, source string) (string, error) {
	target := PluginExecutable(home)
	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		return "", err
	}
	input, err := os.Open(source)
	if err != nil {
		return "", err
	}
	defer input.Close()
	temporary, err := os.CreateTemp(filepath.Dir(target), "."+ExecutableName+".tmp-*")
	if err != nil {
		return "", err
	}
	defer os.Remove(temporary.Name())
	if _, err := io.Copy(temporary, input); err != nil {
		_ = temporary.Close()
		return "", err
	}
	if err := temporary.Chmod(0o755); err != nil {
		_ = temporary.Close()
		return "", err
	}
	if err := temporary.Close(); err != nil {
		return "", err
	}
	if err := os.Rename(temporary.Name(), target); err != nil {
		return "", err
	}
	return target, nil
}

// RepositoryWrapper returns the executable committed for repository plugin
// installs. Source checkouts build from source; plugin copies download the
// pinned release binary once and verify its checksum.
func RepositoryWrapper(version string) string {
	return strings.NewReplacer("{{VERSION}}", version, "{{REPOSITORY}}", Repository).Replace(repositoryWrapperTemplate)
}

// RepositoryWrapperPath returns the committed wrapper path under root.
func RepositoryWrapperPath(root string) string {
	return filepath.Join(root, "extensions", ExtensionName, ExecutableName)
}

// SyncRepositoryWrapper regenerates the committed wrapper for version.
func SyncRepositoryWrapper(root, version string) (string, error) {
	path := RepositoryWrapperPath(root)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return "", err
	}
	if err := os.WriteFile(path, []byte(RepositoryWrapper(version)), 0o755); err != nil {
		return "", err
	}
	if err := os.Chmod(path, 0o755); err != nil {
		return "", fmt.Errorf("make wrapper executable: %w", err)
	}
	return path, nil
}

const repositoryWrapperTemplate = `#!/usr/bin/env sh
# Generated by make sync-version; edit internal/version/VERSION instead.
set -eu

version={{VERSION}}
repository={{REPOSITORY}}
binary_name=kodelet-extension-subagent

extension_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repository_root=$(CDPATH= cd -- "$extension_dir/../.." && pwd)

if [ -f "$repository_root/go.mod" ] && [ -d "$repository_root/cmd/$binary_name" ]; then
  binary="$repository_root/bin/$binary_name"
  mkdir -p "$repository_root/bin"
  (cd "$repository_root" && go build -o "$binary.$$" "./cmd/$binary_name") >&2
  mv -f "$binary.$$" "$binary"
  exec "$binary" "$@"
fi

cache_dir="${XDG_CACHE_HOME:-$HOME/.cache}/kodelet-subagent/$version"
binary="$cache_dir/$binary_name"
if [ ! -x "$binary" ]; then
  os=$(uname -s | tr '[:upper:]' '[:lower:]')
  case "$(uname -m)" in
    x86_64 | amd64) arch=amd64 ;;
    aarch64 | arm64) arch=arm64 ;;
    *)
      echo "kodelet-subagent: unsupported architecture $(uname -m)" >&2
      exit 1
      ;;
  esac
  archive="kodelet-subagent_${version}_${os}_${arch}.tar.gz"
  release_url="https://github.com/$repository/releases/download/v$version"
  mkdir -p "$cache_dir"
  temporary=$(mktemp -d "$cache_dir/.download.XXXXXX")
  trap 'rm -rf "$temporary"' EXIT
  curl -fsSL "$release_url/$archive" -o "$temporary/$archive"
  curl -fsSL "$release_url/checksums.txt" -o "$temporary/checksums.txt"
  expected=$(awk -v name="$archive" '$2 == name { print $1 }' "$temporary/checksums.txt")
  if command -v sha256sum >/dev/null 2>&1; then
    actual=$(sha256sum "$temporary/$archive" | awk '{ print $1 }')
  else
    actual=$(shasum -a 256 "$temporary/$archive" | awk '{ print $1 }')
  fi
  if [ -z "$expected" ] || [ "$expected" != "$actual" ]; then
    echo "kodelet-subagent: checksum mismatch for $archive" >&2
    exit 1
  fi
  tar -xzf "$temporary/$archive" -C "$temporary" "$binary_name"
  chmod 755 "$temporary/$binary_name"
  mv -f "$temporary/$binary_name" "$binary"
  rm -rf "$temporary"
  trap - EXIT
fi
exec "$binary" "$@"
`
